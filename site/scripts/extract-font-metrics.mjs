/**
 * Emits src/lib/cards/font-metrics.ts from the two TTFs the OG route already
 * ships. Run manually when a font file changes:
 *
 *   node scripts/extract-font-metrics.mjs
 *
 * Why a committed table rather than parsing at runtime: card layout has to
 * measure text to decide type size, and that has to work identically in the
 * render script and in the edge route. A table of advance widths is a few KB,
 * needs no dependency, and cannot drift between the two.
 *
 * Minimal TrueType reader — only `head` (unitsPerEm), `hhea` (numberOfHMetrics),
 * `hmtx` (advance widths) and `cmap` format 4 (unicode -> glyph id).
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = join(ROOT, 'src/lib/og/fonts');
const OUT = join(ROOT, 'src/lib/cards/font-metrics.ts');

/** Characters card copy can contain. Anything outside this falls back to the
 *  average width, which is close enough for a size decision. */
const CHARSET = (() => {
  const chars = [];
  for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCharCode(c)); // ASCII printable
  // Punctuation the brand voice actually uses.
  for (const ch of '§·—–…‘’“”€£°×→') chars.push(ch);
  return chars;
})();

function readTables(buf) {
  const numTables = buf.readUInt16BE(4);
  const tables = {};
  for (let i = 0; i < numTables; i++) {
    const p = 12 + i * 16;
    tables[buf.toString('ascii', p, p + 4)] = {
      offset: buf.readUInt32BE(p + 8),
      length: buf.readUInt32BE(p + 12),
    };
  }
  return tables;
}

/** cmap format 4 — the BMP mapping every text font carries. */
function buildCmap(buf, cmapOffset) {
  const numSubtables = buf.readUInt16BE(cmapOffset + 2);
  let best = null;
  for (let i = 0; i < numSubtables; i++) {
    const p = cmapOffset + 4 + i * 8;
    const platformId = buf.readUInt16BE(p);
    const encodingId = buf.readUInt16BE(p + 2);
    const offset = buf.readUInt32BE(p + 4);
    const format = buf.readUInt16BE(cmapOffset + offset);
    if (format !== 4) continue;
    // Prefer Windows/BMP (3,1); accept Unicode (0,*) otherwise.
    const score = platformId === 3 && encodingId === 1 ? 2 : platformId === 0 ? 1 : 0;
    if (!best || score > best.score) best = { score, start: cmapOffset + offset };
  }
  if (!best) throw new Error('no cmap format 4 subtable found');

  const t = best.start;
  const segCount = buf.readUInt16BE(t + 6) / 2;
  const endOf = (i) => buf.readUInt16BE(t + 14 + i * 2);
  const startOf = (i) => buf.readUInt16BE(t + 16 + segCount * 2 + i * 2);
  const deltaOf = (i) => buf.readInt16BE(t + 16 + segCount * 4 + i * 2);
  const rangeOffsetPos = (i) => t + 16 + segCount * 6 + i * 2;

  return (codePoint) => {
    for (let i = 0; i < segCount; i++) {
      if (endOf(i) < codePoint) continue;
      const start = startOf(i);
      if (start > codePoint) return 0;
      const ro = buf.readUInt16BE(rangeOffsetPos(i));
      if (ro === 0) return (codePoint + deltaOf(i)) & 0xffff;
      const gidPos = rangeOffsetPos(i) + ro + (codePoint - start) * 2;
      const gid = buf.readUInt16BE(gidPos);
      return gid === 0 ? 0 : (gid + deltaOf(i)) & 0xffff;
    }
    return 0;
  };
}

function extract(file) {
  const buf = readFileSync(join(FONT_DIR, file));
  const tables = readTables(buf);
  for (const need of ['head', 'hhea', 'hmtx', 'cmap']) {
    if (!tables[need]) throw new Error(`${file}: missing ${need} table`);
  }

  const unitsPerEm = buf.readUInt16BE(tables.head.offset + 18);
  const numberOfHMetrics = buf.readUInt16BE(tables.hhea.offset + 34);
  const lookup = buildCmap(buf, tables.cmap.offset);

  // hmtx holds numberOfHMetrics longHorMetrics; every glyph past that reuses
  // the last advance width.
  const advanceOf = (gid) => {
    const i = Math.min(gid, numberOfHMetrics - 1);
    return buf.readUInt16BE(tables.hmtx.offset + i * 4);
  };

  const widths = {};
  let sum = 0;
  let counted = 0;
  for (const ch of CHARSET) {
    const gid = lookup(ch.codePointAt(0));
    if (!gid) continue; // not in this font
    // Normalise to a 1em scale so callers just multiply by font size.
    const w = advanceOf(gid) / unitsPerEm;
    widths[ch] = Math.round(w * 10000) / 10000;
    sum += w;
    counted++;
  }
  if (counted < 60) throw new Error(`${file}: only ${counted} glyphs resolved — cmap parse looks wrong`);

  return { widths, fallback: Math.round((sum / counted) * 10000) / 10000, unitsPerEm, counted };
}

const serif = extract('InstrumentSerif-Regular.ttf');
const mono = extract('JetBrainsMono-Regular.ttf');

const body = `// GENERATED by scripts/extract-font-metrics.mjs — do not edit by hand.
// Advance widths normalised to a 1em scale: multiply by font size for pixels.
// Source: src/lib/og/fonts/{InstrumentSerif,JetBrainsMono}-Regular.ttf
// Instrument Serif unitsPerEm=${serif.unitsPerEm} (${serif.counted} glyphs) ·
// JetBrains Mono unitsPerEm=${mono.unitsPerEm} (${mono.counted} glyphs)

export interface FontMetrics {
  /** Advance width per character, in em units. */
  widths: Record<string, number>;
  /** Used for characters absent from the table. */
  fallback: number;
}

export const SERIF_METRICS: FontMetrics = ${JSON.stringify(
  { widths: serif.widths, fallback: serif.fallback },
  null,
  2,
)};

export const MONO_METRICS: FontMetrics = ${JSON.stringify(
  { widths: mono.widths, fallback: mono.fallback },
  null,
  2,
)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(
  `wrote ${OUT}\n  serif: ${serif.counted} glyphs, upem ${serif.unitsPerEm}, fallback ${serif.fallback}` +
    `\n  mono:  ${mono.counted} glyphs, upem ${mono.unitsPerEm}, fallback ${mono.fallback}`,
);
